/**
 * The generated project rules file (#1027, doc/design/onboarding-rules-files.md).
 *
 * `pdb onboard` writes `rules.md` from the same compiled English policy `pdb rules` prints, and
 * the managed AGENTS.md section points at it. The file is a dated snapshot, never a competing
 * authority: the marker records the policy identity it was generated from and the header says to
 * consult `pdb rules` for the current policy.
 *
 * The write is guarded like the coordination section: symbolic links are refused, an existing
 * `rules.md` that pdb did not generate is refused rather than overwritten, and identical content
 * is a no-op so repeated onboarding does not touch the tree.
 */
import { lstat } from "node:fs/promises";
import { join } from "node:path";
import { updateTextFile, type UpdateOptions, type WriteOutcome } from "./safejson.js";

/** The file name written in the verified project root. */
export const RULES_FILE_NAME = "rules.md";

/** Prefix of the HTML comment that marks a rules file as generated by pdb. */
export const RULES_FILE_MARKER = "<!-- github-triage:rules-file v1 ";

/** The decision for one existing (or absent) rules file. Pure, so the rules are testable. */
export function withRulesFile(
  text: string | null,
  markdown: string,
): { text: string } | { unchanged: true } | { refuse: string } {
  if (text === null) return { text: markdown };
  if (!text.startsWith(RULES_FILE_MARKER) && !text.includes(`\n${RULES_FILE_MARKER}`))
    return {
      refuse: `${RULES_FILE_NAME} already exists and was not generated by pdb; move it aside or delete it, then retry`,
    };
  if (text === markdown) return { unchanged: true };
  // Generated snapshots are replaced wholesale: the marker proves pdb owns the file, and the
  // header says not to edit it by hand.
  return { text: markdown };
}

/** Install or refresh the generated rules file in the verified project root. */
export async function installRulesFile(
  root: string,
  markdown: string,
  options: UpdateOptions = {},
): Promise<WriteOutcome & { file: string }> {
  const file = RULES_FILE_NAME;
  const path = join(root, file);
  try {
    if ((await lstat(path)).isSymbolicLink())
      return {
        status: "not-written",
        reason: `${file} is a symbolic link; pdb does not write through links`,
        cleanup: [],
        file,
      };
  } catch (error) {
    if ((error as { code?: unknown }).code !== "ENOENT")
      return { status: "not-written", reason: `${file} cannot be inspected`, cleanup: [], file };
  }
  const outcome = await updateTextFile(
    path,
    (current) => {
      if (current.state === "unreadable") return { refuse: `${file} ${current.why}` };
      const next = withRulesFile(current.state === "text" ? current.text : null, markdown);
      if ("refuse" in next) return { refuse: next.refuse };
      if ("unchanged" in next) return { keep: `${file} already has the current generated rules` };
      return { write: next.text };
    },
    { ...options, checkUnchanged: true },
  );
  return { ...outcome, file };
}
