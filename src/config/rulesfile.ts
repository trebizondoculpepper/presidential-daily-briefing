/**
 * The generated project rules file (#1027, doc/design/onboarding-rules-files.md).
 *
 * `pdb onboard` writes `rules.md` from the same compiled English policy `pdb rules` prints, and
 * the managed AGENTS.md section points at it. The file is a dated snapshot, never a competing
 * authority: the marker records the policy identity it was generated from and the header says to
 * consult `pdb rules` for the current policy.
 *
 * The write is guarded like the coordination section: symbolic links are refused, an existing
 * `rules.md` that pdb did not generate is refused rather than overwritten, and identical content
 * is a no-op so repeated onboarding does not touch the tree.
 */
import { createHash } from "node:crypto";
import { lstat, readdir } from "node:fs/promises";
import { join } from "node:path";
import { updateTextFile, type UpdateOptions, type WriteOutcome } from "./safejson.js";

/** The file name written in the verified project root. */
export const RULES_FILE_NAME = "rules.md";

/** Prefix of the HTML comment that marks a rules file as generated by pdb. */
export const RULES_FILE_MARKER = "<!-- github-triage:rules-file v1 ";

/** Everything after the marker line: the generated header and document. */
const tailOf = (text: string): string => {
  const newline = text.indexOf("\n");
  return newline === -1 ? "" : text.slice(newline + 1);
};
const sha256 = (value: string): string => createHash("sha256").update(value).digest("hex");

const markerJson = (text: string): Record<string, unknown> | null => {
  if (!text.startsWith(RULES_FILE_MARKER)) return null;
  const end = text.indexOf(" -->");
  if (end === -1) return null;
  try {
    const parsed = JSON.parse(text.slice(RULES_FILE_MARKER.length, end));
    return typeof parsed === "object" && parsed !== null ? parsed : null;
  } catch {
    return null;
  }
};

/**
 * Seal a freshly generated rules document with the fingerprint of its own content, so a later
 * run can tell an untouched generated file from one a person edited (reviewed #1195 finding:
 * the policy hash identifies the policy, never the file's contents).
 */
export function sealRulesMarkdown(markdown: string): string {
  const marker = markerJson(markdown);
  if (!marker) return markdown;
  const tail = tailOf(markdown);
  const sealed = { ...marker, contentSha256: sha256(tail) };
  const firstLine = `${RULES_FILE_MARKER}${JSON.stringify(sealed)} -->`;
  return [firstLine, ...markdown.split("\n").slice(1)].join("\n");
}

/** Whether a generated file was edited after generation, by its own fingerprint. */
export function rulesFileEdited(text: string): boolean {
  const marker = markerJson(text);
  const digest = marker?.contentSha256;
  if (typeof digest !== "string") return false;
  return digest !== sha256(tailOf(text));
}

/** The decision for one existing (or absent) rules file. Pure, so the rules are testable. */
export function withRulesFile(
  text: string | null,
  markdown: string,
): { text: string } | { unchanged: true } | { refuse: string } {
  if (text === null) return { text: markdown };
  if (markerJson(text) === null)
    return {
      refuse: `${RULES_FILE_NAME} already exists and was not generated by pdb; move it aside or delete it, then retry`,
    };
  if (text === markdown) return { unchanged: true };
  // Edits to a generated snapshot are preserved, never silently discarded: the file keeps its
  // fingerprint, so a changed body proves someone edited it.
  if (rulesFileEdited(text))
    return {
      refuse: `${RULES_FILE_NAME} was edited after pdb generated it; move it aside or restore the generated content, then retry`,
    };
  return { text: markdown };
}

/** Why a case-colliding name refuses the write, or null when the root is unambiguous. */
async function caseCollision(root: string): Promise<string | null> {
  let names: string[];
  try {
    names = await readdir(root);
  } catch {
    return null; // A missing root is reported by the writer itself.
  }
  const other = names.find((n) => n.toLowerCase() === RULES_FILE_NAME && n !== RULES_FILE_NAME);
  return other
    ? `${other} already exists; pdb writes only ${RULES_FILE_NAME}, so keep one name and retry`
    : null;
}

/** Whether the root already holds a differently-cased rules file (#1027 review). */
export const rulesFileCaseCollision = caseCollision;

/** Install or refresh the generated rules file in the verified project root. */
export async function installRulesFile(
  root: string,
  markdown: string,
  options: UpdateOptions = {},
): Promise<WriteOutcome & { file: string }> {
  const file = RULES_FILE_NAME;
  const collision = await caseCollision(root);
  if (collision) return { status: "not-written", reason: collision, cleanup: [], file };
  const path = join(root, file);
  try {
    if ((await lstat(path)).isSymbolicLink())
      return {
        status: "not-written",
        reason: `${file} is a symbolic link; pdb does not write through links`,
        cleanup: [],
        file,
      };
  } catch (error) {
    if ((error as { code?: unknown }).code !== "ENOENT")
      return { status: "not-written", reason: `${file} cannot be inspected`, cleanup: [], file };
  }
  const outcome = await updateTextFile(
    path,
    (current) => {
      if (current.state === "unreadable") return { refuse: `${file} ${current.why}` };
      const next = withRulesFile(current.state === "text" ? current.text : null, markdown);
      if ("refuse" in next) return { refuse: next.refuse };
      if ("unchanged" in next) return { keep: `${file} already has the current generated rules` };
      return { write: next.text };
    },
    { ...options, checkUnchanged: true },
  );
  return { ...outcome, file };
}
